"""Generate docs/TOOLS.md from the MCP server's own tool definitions (single source of truth).

Usage:  python scripts/gen_tools_doc.py
"""
import asyncio
import re
from pathlib import Path

from daily_tutor.server import mcp

GROUPS = [
    ("Setup and preferences", ["set_preferences", "set_topic", "remove_topic", "set_question_types",
                               "list_question_types", "set_settings", "get_preferences"]),
    ("Certification tracks", ["list_tracks", "start_track", "get_coverage"]),
    ("Your own material", ["add_material", "list_materials", "remove_material"]),
    ("Asking questions", ["get_next_question_brief", "save_question"]),
    ("Sessions", ["start_session", "get_session"]),
    ("Evaluating answers", ["get_pending_question", "check_answer", "record_result", "use_hint", "skip_question"]),
    ("Progress and review", ["get_progress", "weekly_recap", "review_mistakes", "get_due_reviews"]),
]


def one_line(text: str) -> str:
    return re.sub(r"\s+", " ", text or "").strip()


def params(schema: dict) -> str:
    props, required = schema.get("properties", {}), set(schema.get("required", []))
    parts = []
    for name, spec in props.items():
        if name == "user_id":
            continue
        kind = spec.get("type") or "/".join(x.get("type", "?") for x in spec.get("anyOf", [])) or "any"
        parts.append(f"`{name}`{'' if name in required else '?'}: {kind}")
    return ", ".join(parts) or "none"


async def main() -> None:
    tools = {t.name: t for t in await mcp.list_tools()}
    prompts = await mcp.list_prompts()
    seen: set[str] = set()
    out = ["# Tool reference", "",
           "> Generated by `python scripts/gen_tools_doc.py`. Do not edit by hand.", "",
           "Every tool also accepts an optional `user_id` (stdio mode only; ignored over authenticated HTTP).",
           "A trailing `?` marks an optional parameter.", ""]
    for title, names in GROUPS:
        out += [f"## {title}", "", "| Tool | Parameters | What it does |", "|---|---|---|"]
        for n in names:
            t = tools[n]
            seen.add(n)
            out.append(f"| `{n}` | {params(t.inputSchema)} | {one_line(t.description).replace('|', '/')} |")
        out.append("")
    missing = set(tools) - seen
    if missing:
        raise SystemExit(f"Tools missing from GROUPS: {sorted(missing)}")
    out += ["## Prompts", "", "| Prompt | Purpose |", "|---|---|"]
    out += [f"| `{p.name}` | {one_line(p.description)} |" for p in prompts]
    Path("docs/TOOLS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"docs/TOOLS.md written: {len(tools)} tools, {len(prompts)} prompts")


if __name__ == "__main__":
    asyncio.run(main())
